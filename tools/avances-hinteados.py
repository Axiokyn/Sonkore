#!/usr/bin/env python3
"""The few Inter glyphs whose hinted advance (FreeType full hinting at the
logical pixel size) is not the design advance
rounded, which is what equalizer_ui.rs::hinted_width uses. Writes them as a table
to crates/app/src/hinted_advances.rs. "Sistema" at 10 px, weight 600: hinted 41 px, the
rounded advances 40 (the 's').

    <python with freetype-py and fontTools> tools/avances-hinteados.py

Run again if the Inter fonts change.
"""
from pathlib import Path

import freetype

REPO = Path(__file__).resolve().parent.parent
FONTS = REPO / "fonts" / "inter"
OUT = REPO / "crates" / "app" / "src" / "hinted_advances.rs"
WEIGHTS = (400, 500, 600, 700)
SIZES = range(9, 17)
CHARS = [chr(c) for c in range(0x20, 0x7F)] + [chr(c) for c in range(0xA0, 0x180)] \
    + list("‐‑–—‘’‚“”„•…‰‹›€−→←↑↓✓×")


def main():
    rows = []
    for w in WEIGHTS:
        face = freetype.Face(str(FONTS / f"{w}.ttf"))
        upm = face.units_per_EM
        for px in SIZES:
            face.set_pixel_sizes(0, px)
            for c in CHARS:
                if not face.get_char_index(c):
                    continue
                face.load_char(c, freetype.FT_LOAD_NO_SCALE)
                design = round(face.glyph.advance.x * px / upm)
                face.load_char(c, freetype.FT_LOAD_DEFAULT)
                hinted = face.glyph.advance.x // 64
                if hinted != design:
                    rows.append((w, px, c, hinted))
    lines = [
        "// Generated by tools/avances-hinteados.py: Inter glyphs whose hinted advance",
        "// (FreeType full hinting at the logical size) is not the design advance rounded.",
        "// (weight, pixel size, char, advance in px)",
        "pub const HINTED: &[(u16, u8, char, u8)] = &[",
    ]
    for w, px, c, adv in rows:
        lines.append(f"    ({w}, {px}, '\\u{{{ord(c):04x}}}', {adv}), // {c}")
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(rows)} glifos → {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
